import Foundation

/// Renders the current scheme as a kitty theme include (`~/.config/kitty/caelestia-theme.conf`).
///
/// Mapping (spec section 6): `term0-15` → `color0-15`, `background = surface`, `foreground = onSurface`,
/// `cursor = onSurface`, `cursor_text_color = surface`, `selection_background = surfaceContainerHigh`,
/// `selection_foreground = onSurface`, `url_color = primary`, `active_border_color = primary`,
/// `inactive_border_color = outlineVariant`, active tab = `onPrimary` on `primary`, inactive tab =
/// `onSurfaceVariant` on `surfaceContainer`, `cursor_trail_color = onSurfaceVariant` (Gabby's
/// kitty.conf enables `cursor_trail`). Reloading running kittys (`SIGUSR1`) is the Platform module's job.
public enum KittyThemeWriter {
    /// First line of every generated file; the installer uses it to recognise our file.
    public static let headerMarker = "# generated by Caelestia for Mac; do not edit"

    /// Fallback roles when a scheme lacks a `term<i>` colour (built-in schemes define all 16).
    static let terminalFallbacks: [ColorRole] = [
        .surfaceContainerHighest, .error, .success, .tertiary, .primary, .secondary, .tertiary, .onSurfaceVariant,
        .outline, .error, .success, .tertiary, .primary, .secondary, .tertiary, .onSurface,
    ]

    /// The kitty config text for `scheme`.
    public static func render(scheme: Scheme) -> String {
        var lines: [String] = []
        lines.append(headerMarker)
        lines.append("# scheme: \(scheme.name) (\(scheme.flavour), \(scheme.mode)); regenerated on every scheme change")
        lines.append("")
        for i in 0..<16 {
            let color = scheme.term(i) ?? scheme[terminalFallbacks[i]]
            lines.append("color\(i) #\(color.hex)")
        }
        lines.append("")
        let pairs: [(String, RGBA)] = [
            ("background", scheme[.surface]),
            ("foreground", scheme[.onSurface]),
            ("cursor", scheme[.onSurface]),
            ("cursor_text_color", scheme[.surface]),
            ("cursor_trail_color", scheme[.onSurfaceVariant]),
            ("selection_background", scheme[.surfaceContainerHigh]),
            ("selection_foreground", scheme[.onSurface]),
            ("url_color", scheme[.primary]),
            ("active_border_color", scheme[.primary]),
            ("inactive_border_color", scheme[.outlineVariant]),
            ("active_tab_foreground", scheme[.onPrimary]),
            ("active_tab_background", scheme[.primary]),
            ("inactive_tab_foreground", scheme[.onSurfaceVariant]),
            ("inactive_tab_background", scheme[.surfaceContainer]),
        ]
        for (key, color) in pairs {
            lines.append("\(key) #\(color.hex)")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// Writes ``render(scheme:)`` atomically to `url`, creating parent directories.
    public static func write(scheme: Scheme, to url: URL = Paths.kittyThemeFile) throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Data(render(scheme: scheme).utf8).write(to: url, options: .atomic)
    }

    /// Parses a kitty theme file (`key #rrggbb` lines) into a dictionary; used by tests and the
    /// installer to compare an existing theme with what we would write.
    public static func parse(_ text: String) -> [String: RGBA] {
        var result: [String: RGBA] = [:]
        for rawLine in text.split(whereSeparator: \.isNewline) {
            let line = rawLine.trimmingCharacters(in: .whitespaces)
            guard !line.isEmpty, !line.hasPrefix("#") else { continue }
            let parts = line.split(whereSeparator: \.isWhitespace)
            guard parts.count >= 2, let color = RGBA(hex: String(parts[1])) else { continue }
            result[String(parts[0])] = color
        }
        return result
    }
}
